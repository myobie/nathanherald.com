// Shared pieces for drawing rolls of film: the roll.json types, film formats,
// date formatting, and the markup for a single frame on a strip. Used by
// <nh-contact-sheet> (one roll) and <nh-roll-list> (the photos index).

export interface Frame {
  n: number
  assetId?: string
  filename?: string
  rating: number
  flag: number
  width: number
  height: number
  thumb: string | null
  image: string | null
  imageLongSide: number | null
}

export interface Roll {
  slug: string
  title: string
  film: string | null
  format: string
  camera: string | null
  shot: string | null
  scanned: string | null
  notes: string | null
  frames: Frame[]
}

/** An entry in rolls.json, the index of all rolls generated by the build. */
export interface RollSummary extends Omit<Roll, 'frames' | 'notes'> {
  url: string
  frameCount: number
  keepers: number
  preview: Frame[]
}

export interface FormatSpec {
  // frames per uncut strip, and per row on narrow screens
  perStrip: number
  perStripNarrow: number
  // aspect of the exposure area (width / height)
  aspect: number
  // sprocket holes per frame edge, 0 for roll film without perforations
  perfs: number
  label: string
}

export const FORMATS: Record<string, FormatSpec> = {
  '35mm': { perStrip: 6, perStripNarrow: 3, aspect: 3 / 2, perfs: 8, label: '35mm' },
  'half-frame': { perStrip: 12, perStripNarrow: 6, aspect: 2 / 3, perfs: 4, label: 'Half frame' },
  '120-6x6': { perStrip: 3, perStripNarrow: 3, aspect: 1, perfs: 0, label: '120, 6×6' },
  '120-6x4.5': { perStrip: 4, perStripNarrow: 2, aspect: 3 / 4, perfs: 0, label: '120, 6×4.5' },
  '120-6x7': { perStrip: 3, perStripNarrow: 2, aspect: 7 / 6, perfs: 0, label: '120, 6×7' },
  '110': { perStrip: 6, perStripNarrow: 3, aspect: 17 / 13, perfs: 1, label: '110' },
}

export function formatSpec(format: string): FormatSpec {
  return FORMATS[format] ?? FORMATS['35mm']
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December']

export function formatMonth(value: string) {
  const [y, m] = value.split('-')
  return m ? `${MONTHS[parseInt(m, 10) - 1]} ${y}` : y
}

export function formatDay(value: string) {
  const [y, m, d] = value.split('T')[0].split('-')
  if (!d) return formatMonth(value)
  return `${parseInt(d, 10)} ${MONTHS[parseInt(m, 10) - 1]}, ${y}`
}

/** "Ilford Delta 400 · Pentax P30t · 35mm · December 2025" */
export function factsLine(roll: Pick<Roll, 'film' | 'camera' | 'format' | 'shot'>) {
  const facts: string[] = []
  if (roll.film) facts.push(roll.film)
  if (roll.camera) facts.push(roll.camera)
  facts.push(formatSpec(roll.format).label)
  if (roll.shot) facts.push(formatMonth(roll.shot))
  return facts.join(' · ')
}

export type El = (tag: string, attrs?: Record<string, string>, ...kids: (Node | string)[]) => HTMLElement

export function elFactory(doc: Document): El {
  return (tag, attrs = {}, ...kids) => {
    const e = doc.createElement(tag)
    for (const [k, v] of Object.entries(attrs)) e.setAttribute(k, v)
    for (const k of kids) e.append(typeof k === 'string' ? doc.createTextNode(k) : k)
    return e
  }
}

/** The <div class="contact-sheet"> wrapper, which carries the format as CSS variables. */
export function sheetElement(el: El, format: string, extraClass = '') {
  const spec = formatSpec(format)
  const aspect = (spec.aspect * 1000).toFixed(1)
  return el('div', {
    class: `contact-sheet format-${format.replace(/[^a-z0-9-]/gi, '')}${spec.perfs ? '' : ' no-perfs'}${extraClass ? ' ' + extraClass : ''}`,
    style: `--per-strip: ${spec.perStrip}; --per-strip-narrow: ${spec.perStripNarrow}; --frame-aspect: ${aspect} / 1000; --perfs: ${spec.perfs};`,
  })
}

export interface FrameOptions {
  edge: string
  cellAspect: number
  // where clicking the frame goes; defaults to the large image
  href?: string | null
  // extra classes for the figure
  className?: string
  id?: string
}

/**
 * One frame on a strip: rebate with edge text, the exposure, and rebate with
 * frame numbers. Returns the figure and its exposure, so callers can add a mark.
 */
export function frameElement(el: El, frame: Frame, opts: FrameOptions) {
  const portrait = frame.height > frame.width
  // A vertical shot on a horizontal roll (or the reverse on half frame) sits
  // sideways on the film, so it's drawn rotated to fill the frame, like a
  // real contact sheet.
  const rotated = opts.cellAspect !== 1 && portrait === (opts.cellAspect > 1)
  const label = `Frame ${frame.n}` + (frame.rating ? `, ${frame.rating} star${frame.rating === 1 ? '' : 's'}` : '')

  const attrs: Record<string, string> = {
    class: 'frame' + (portrait ? ' portrait' : '') + (rotated ? ' rotated' : '') + (opts.className ? ` ${opts.className}` : ''),
    'data-rating': String(frame.rating),
  }
  if (opts.id) attrs.id = opts.id
  const fig = el('figure', attrs)

  const top = el('div', { class: 'rebate rebate-top', 'aria-hidden': 'true' })
  if (opts.edge && frame.n % 2 === 1) top.append(el('span', { class: 'edge-text' }, opts.edge))

  const exposure = el('div', { class: 'exposure' })
  const thumb = frame.thumb ?? frame.image
  const href = opts.href === undefined ? frame.image : opts.href
  if (thumb) {
    const img = el('img', {
      src: thumb,
      alt: label,
      loading: 'lazy',
      decoding: 'async',
      width: String(portrait ? Math.round(640 * frame.width / frame.height) : 640),
      height: String(portrait ? 640 : Math.round(640 * frame.height / frame.width)),
    })
    exposure.append(href ? el('a', { href, class: 'never-underline' }, img) : img)
  } else {
    exposure.append(el('span', { class: 'no-scan' }, 'no scan'))
  }

  const bottom = el('div', { class: 'rebate rebate-bottom', 'aria-hidden': 'true' },
    el('span', { class: 'frame-number' }, String(frame.n)),
    el('span', { class: 'frame-number frame-number-a' }, `${frame.n}A`),
  )

  fig.append(top, exposure, bottom)
  return { fig, exposure }
}
